import { describe, expect, it } from 'vitest';
import {
  compareVersions,
  engineVersionFromPath,
  parseWindhawkIni,
  pickHighestVersion,
} from '@core/environment/windhawk-ini';
import { readFixture } from '../domain/test-fixtures';

describe('parseWindhawkIni', () => {
  it('parses the installed registry-mode configuration', () => {
    const parsed = parseWindhawkIni(readFixture('windhawk/registry.ini'));

    expect(parsed).toEqual({
      portable: false,
      registryKey: 'HKLM\\SOFTWARE\\Windhawk',
      appDataPath: '%ProgramData%\\Windhawk',
      enginePath: 'Engine\\1.7.3',
    });
  });

  it('parses portable mode and a custom registry root', () => {
    const parsed = parseWindhawkIni(readFixture('windhawk/portable.ini'));

    expect(parsed.portable).toBe(true);
    expect(parsed.registryKey).toBe('HKCU\\SOFTWARE\\Windhawk');
  });

  it('is case-insensitive, ignores comments, and strips quotes', () => {
    const parsed = parseWindhawkIni(
      '\uFEFF; generated by Windhawk\r\n[Storage]\r\nportable = "true"\r\nRegistryKey = "HKLM\\SOFTWARE\\Windhawk"\r\nEnginePath = Engine\\1.7.3\r\n',
    );

    expect(parsed).toEqual({
      portable: true,
      registryKey: 'HKLM\\SOFTWARE\\Windhawk',
      appDataPath: null,
      enginePath: 'Engine\\1.7.3',
    });
  });

  it('treats malformed lines and unknown sections as absent values', () => {
    const parsed = parseWindhawkIni('[Other]\nPortable=1\n[Storage]\nnot-a-pair\n');

    expect(parsed.portable).toBe(false);
    expect(parsed.registryKey).toBeNull();
    expect(parsed.enginePath).toBeNull();
  });
});

describe('engine versions', () => {
  it('extracts a version from a relative or absolute engine path', () => {
    expect(engineVersionFromPath('Engine\\1.7.3')).toBe('1.7.3');
    expect(engineVersionFromPath('C:\\Program Files\\Windhawk\\Engine\\10.2')).toBe('10.2');
    expect(engineVersionFromPath('Engine')).toBeNull();
    expect(engineVersionFromPath(null)).toBeNull();
  });

  it('compares numeric versions and selects the highest', () => {
    expect(compareVersions('1.7.3', '1.7.2')).toBeGreaterThan(0);
    expect(compareVersions('1.10.0', '1.9.9')).toBeGreaterThan(0);
    expect(compareVersions('1.7.3', '1.7.3')).toBe(0);
    expect(pickHighestVersion(['1.6.9', '1.10.0', 'not-a-version', '1.7.3'])).toBe('1.10.0');
    expect(pickHighestVersion([])).toBeNull();
  });
});
